def t(key, lang, **kwargs):
    """Get translated string. Falls back to English if key/lang missing."""
    val = STRINGS.get(key, {}).get(lang) or STRINGS.get(key, {}).get("english", key)
    if kwargs:
        val = val.format(**kwargs)
    return val

def fetch_live_translations(lang_code_map=None):
    import json, os
    cache_file = "translations_cache.json"

    # Agar cache already hai, load karo aur skip karo
    if os.path.isfile(cache_file):
        try:
            with open(cache_file, "r", encoding="utf-8") as f:
                cached = json.load(f)
            for key, translations in cached.items():
                if key in STRINGS:
                    STRINGS[key].update(translations)
            print("[Trans] Loaded from cache.")
            return
        except Exception as e:
            print(f"[Trans] Cache load failed: {e}, re-fetching...")

    # Cache nahi hai — fresh translate karo
    try:
        from googletrans import Translator
        translator = Translator()

        lang_codes = {
            "hindi":   "hi",
            "marathi": "mr",
            "punjabi": "pa",
            "bengali": "bn",
            "telugu":  "te",
        }

        print("[Trans] Fetching translations (one-time)...")
        cache_data = {}
        for key, translations in STRINGS.items():
            english_text = translations.get("english", "")
            if not english_text:
                continue
            cache_data[key] = {}
            for lang, code in lang_codes.items():
                try:
                    result = translator.translate(english_text, dest=code)
                    STRINGS[key][lang] = result.text
                    cache_data[key][lang] = result.text
                    print(f"[Trans] {key} → {lang}: {result.text}")
                except Exception as e:
                    print(f"[Trans] Failed {key}/{lang}: {e}")

        # Cache save karo
        with open(cache_file, "w", encoding="utf-8") as f:
            json.dump(cache_data, f, ensure_ascii=False, indent=2)
        print("[Trans] Done. Cached for future runs.")

    except Exception as e:
        print(f"[Trans] Disabled: {e}")